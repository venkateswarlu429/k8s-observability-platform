#!/usr/bin/env python3
"""Wrap dashboards/*.json into Grafana sidecar ConfigMaps.

The kube-prometheus-stack values in helm/ enable Grafana's dashboard
sidecar with label `grafana_dashboard="1"`. Each dashboard JSON becomes
one ConfigMap in manifests/dashboards/, ready for:

    kubectl apply -f manifests/dashboards/

Re-run this script after editing anything in dashboards/ — the JSON files
are the source of truth, the ConfigMaps are generated artifacts.

    python3 scripts/sync-dashboard-configmaps.py
"""
import json
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "dashboards"
DST = ROOT / "manifests" / "dashboards"
NAMESPACE = "monitoring"


class LiteralStr(str):
    """A string PyYAML should emit as a literal block (|)."""


def literal_representer(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")


yaml.add_representer(LiteralStr, literal_representer, Dumper=yaml.SafeDumper)


def main() -> int:
    DST.mkdir(parents=True, exist_ok=True)
    for path in sorted(SRC.glob("*.json")):
        raw = path.read_text()
        json.loads(raw)  # fail loudly on broken JSON instead of shipping it
        configmap = {
            "apiVersion": "v1",
            "kind": "ConfigMap",
            "metadata": {
                "name": f"grafana-dashboard-{path.stem}",
                "namespace": NAMESPACE,
                "labels": {
                    # This label is the contract with the Grafana sidecar
                    # configured in helm/values-kube-prometheus-stack.yaml.
                    "grafana_dashboard": "1",
                    "app.kubernetes.io/part-of": "observability-platform",
                },
                "annotations": {
                    "grafana_folder": "Platform",
                    "observability.example/source": f"dashboards/{path.name} (generated — edit the JSON, then re-run scripts/sync-dashboard-configmaps.py)",
                },
            },
            "data": {path.name: LiteralStr(raw if raw.endswith("\n") else raw + "\n")},
        }
        out = DST / f"{path.stem}.yaml"
        out.write_text(
            "# Generated by scripts/sync-dashboard-configmaps.py — do not edit by hand.\n"
            + yaml.safe_dump(configmap, sort_keys=False, width=10_000)
        )
        print(f"{path.name} -> manifests/dashboards/{out.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
